/**
 * A text in the language, with `{name}` replaced
 *
 * @param lang language of the system
 * @param key key of the text
 * @param values the placeholders
 */
export function text(lang: ioBroker.Languages, key: string, values: Record<string, string | number> = {}): string {
    const template = TEXTS[lang]?.[key] ?? TEXTS.en[key] ?? key;
    return template.replace(/\{(\w+)}/g, (match, name: string) =>
        values[name] !== undefined ? String(values[name]) : match,
    );
}
